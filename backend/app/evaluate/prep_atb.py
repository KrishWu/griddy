def wtk_cross_check() -> str:
    """Recompute the Tehachapi WTK statistics if the raw metadata file is present."""
    if not RAW_WTK.exists():
        return f"skipped (no {RAW_WTK.name}; download from {DOC_FACTS['tehachapi_wind_speed']['url']})"
    raw = RAW_WTK.read_text().replace("\r", "\n")  # the file uses bare CR line endings
    w = pd.read_csv(io.StringIO(raw))
    f = DOC_FACTS["tehachapi_wind_speed"]["site_filter"]
    sites = w[(w["State"] == f["State"]) & (w["County"] == f["County"])
              & w["latitude"].between(f["lat_min"], f["lat_max"]) & w["longitude"].between(f["lon_min"], f["lon_max"])]
    mean = round(float(sites["wind_speed"].mean()), 3)
    expected = DOC_FACTS["tehachapi_wind_speed"]["value"]
    if len(sites) != DOC_FACTS["tehachapi_wind_speed"]["n_sites"] or abs(mean - expected) > 1e-3:
        raise ValueError(f"WTK recompute ({len(sites)} sites, {mean} m/s) != DOC_FACTS ({expected} m/s)")
    return f"ok ({len(sites)} sites, mean {mean} m/s at 100 m)"


def sanity_checks(cat: dict[str, Any]) -> list[tuple[str, bool, str]]:
    t = cat["techs"]
    pv = t["solar_pv"]["derived"]["capex_ex_gcc_usd_per_kw"] * APPROX_DEFLATOR_2023_TO_2024
    r2 = t["battery"]["derived"]["fit_r2"]
    rte = t["battery"]["parameters"]["Round-Trip Efficiency"]["value"]
    hr_cc = t["gas_cc"]["parameters"]["Heat Rate"]["value"]
    hr_ct = t["gas_ct"]["parameters"]["Heat Rate"]["value"]
    traj_ok = all(len(x["capex_ex_gcc_trajectory_usd_per_kw"]) == len(TRAJECTORY_YEARS) for x in t.values())
    return [
        ("PV capex_ex_gcc x1.03 in $1,200-1,800/kW", 1200 <= pv <= 1800, f"{pv:,.0f} $/kW (approx. 2024$)"),
        ("battery fit R^2 > 0.99", r2 > 0.99, f"{r2:.6f}"),
        ("battery RTE in 0.80-0.90", 0.8 <= rte <= 0.9, f"{rte}"),
        ("gas CC heat rate ~6 MMBtu/MWh", 5.5 <= hr_cc <= 6.5, f"{hr_cc}"),
        ("gas CT heat rate ~9.7 MMBtu/MWh", 9.2 <= hr_ct <= 10.2, f"{hr_ct}"),
        ("trajectories cover 2027-2060", traj_ok, f"{len(TRAJECTORY_YEARS)} years"),
    ]


def print_summary(cat: dict[str, Any]) -> None:
    head = f"{'kind':<13}{'ATB detail':<38}{'case':<5}{'CAPEX':>8}{'ex GCC':>8}{'FOM':>7}{'VOM':>6}{'HR':>7}{'CF/RTE':>8}{'life':>5}"
    print(f"ATB 2025 v1.0.0, {SCENARIO}, COD {COD_YEAR}, crpyears {CRP_YEARS}, no tax credits, {DOLLAR_YEAR} USD")
    print(head)
    print("-" * len(head))
    for kind, x in cat["techs"].items():
        p = x["parameters"]
        perf = p.get("CF", p.get("Round-Trip Efficiency"))
        print(
            f"{kind:<13}{x['atb']['display_name'][:37]:<38}{x['atb']['core_metric_case']:<5}"
            f"{p['CAPEX']['value']:>8.1f}{x['derived']['capex_ex_gcc_usd_per_kw']:>8.1f}"
            f"{p['Fixed O&M']['value']:>7.2f}"
            f"{p['Variable O&M']['value'] if 'Variable O&M' in p else 0:>6.2f}"
            f"{p['Heat Rate']['value'] if 'Heat Rate' in p else 0:>7.3f}"
            f"{perf['value'] if perf else 0:>8.4f}{x['lifetime_years']:>5}"
        )
    b = cat["techs"]["battery"]["derived"]
    print(f"battery split: {b['power_usd_per_kw']:.2f} $/kW + {b['energy_usd_per_kwh']:.2f} $/kWh x h "
          f"(R^2 {b['fit_r2']:.6f}, max residual {b['fit_max_abs_residual_usd_per_kw']:.3f} $/kW)")
    for kind in ("solar_pv", "onshore_wind", "battery"):
        tr = cat["techs"][kind]["capex_ex_gcc_trajectory_usd_per_kw"]
        print(f"{kind} capex_ex_gcc: 2027 {tr['2027']:.0f}, 2030 {tr['2030']:.0f}, 2040 {tr['2040']:.0f}, 2060 {tr['2060']:.0f} $/kW")


def main() -> None:
    df = load_atb()
    catalog = build_catalog(df)
    print_summary(catalog)
    print(f"WTK cross-check: {wtk_cross_check()}")
    checks = sanity_checks(catalog)
    for name, ok, detail in checks:
        print(f"[{'ok' if ok else 'FAIL'}] {name}: {detail}")
    if not all(ok for _, ok, _ in checks):
        raise SystemExit("sanity checks failed; catalog not written")
    OUT_JSON.write_text(json.dumps(catalog, indent=2, ensure_ascii=False, allow_nan=False) + "\n")
    print(f"wrote {OUT_JSON}")


if __name__ == "__main__":
    main()
