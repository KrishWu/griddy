def battery(df: pd.DataFrame) -> dict[str, Any]:
    technology = "Utility-Scale Battery Storage"
    by_duration: dict[str, dict[str, Any]] = {}
    capex_points: list[float] = []
    fom_points: list[float] = []
    for d in BATTERY_DURATIONS_H:
        rows = rows_at(df, technology, f"{d}Hr Battery Storage", COD_YEAR)
        params = parameters(rows, (*CAPEX_PARTS, "Fixed O&M"))
        check_capex_identity(rows, f"battery {d}h {COD_YEAR}")
        by_duration[str(d)] = params | {"capex_ex_gcc_usd_per_kw": {"value": rnd(derived_capex(rows)), "units": "$/kW"}}
        capex_points.append(derived_capex(rows))
        fom_points.append(raw(rows, "Fixed O&M"))

    ref_td = f"{BATTERY_REFERENCE_H}Hr Battery Storage"
    rows = rows_at(df, technology, ref_td, COD_YEAR)
    rte = rows_at(df, technology, "*", COD_YEAR, display_name=f"Utility-Scale Battery Storage - {BATTERY_REFERENCE_H}Hr")
    rows["Round-Trip Efficiency"] = rte["Round-Trip Efficiency"]
    params = parameters(rows, PARAMETERS_BY_KIND["battery"])
    params["Round-Trip Efficiency"]["doc"] = doc_ref(DOC_FACTS["battery_rte"])

    power, energy, r2 = linear_fit(list(BATTERY_DURATIONS_H), capex_points)
    fom_power, fom_energy, fom_r2 = linear_fit(list(BATTERY_DURATIONS_H), fom_points)
    residuals = [abs(power + energy * d - y) for d, y in zip(BATTERY_DURATIONS_H, capex_points)]
    life, life_src = lifetime("battery")
    derived = rnd(derived_capex(rows))
    traj = trajectory(df, technology, ref_td)
    if traj[str(COD_YEAR)] != derived:
        raise ValueError(f"battery: trajectory {COD_YEAR} {traj[str(COD_YEAR)]} != derived {derived}")
    return {
        "label": f"Utility-scale Li-ion (LFP) battery storage (ATB, {BATTERY_REFERENCE_H} h reference)",
        "atb": atb_block(rows["CAPEX"], technology),
        "parameters": params,
        "parameters_by_duration_h": by_duration,
        "derived": {
            "capex_ex_gcc_usd_per_kw": derived,
            "formula": "OCC + CFC*OCC/(OCC+GCC)",
            "power_usd_per_kw": rnd(power),
            "energy_usd_per_kwh": rnd(energy),
            "fit_r2": round(r2, 8),
            "fit_max_abs_residual_usd_per_kw": rnd(max(residuals)),
            "fit_formula": "capex_ex_gcc(d) = power_usd_per_kw + energy_usd_per_kwh * d, least squares over d = 2,4,6,8,10 h",
            "fit_points": [{"duration_h": d, "capex_ex_gcc_usd_per_kw": rnd(y)} for d, y in zip(BATTERY_DURATIONS_H, capex_points)],
            "fixed_om_power_usd_per_kw_yr": rnd(fom_power),
            "fixed_om_energy_usd_per_kwh_yr": rnd(fom_energy),
            "fixed_om_fit_r2": round(fom_r2, 8),
        },
        "capex_ex_gcc_trajectory_usd_per_kw": traj,
        "trajectory_basis": f"{BATTERY_REFERENCE_H} h configuration, total $/kW",
        "lifetime_years": life,
        "lifetime_source": life_src,
    }


