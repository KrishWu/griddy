"""Extract the NLR ATB 2025 technology catalog.  OWNER: workstream C (Evaluate).

Run from backend/:  .venv/bin/python -m app.evaluate.prep_atb

Input   data/evaluate/raw/ATBe_2025_v1.0.0.csv  (git-ignored, ~320 MB, download from ATB_CSV_URL)
Output  data/evaluate/atb_2025_catalog.json     (committed; catalog.py loads it)

Selection rules:
- Scenario "Moderate", commercial operation (COD) year 2027 (ATB's core_metric_variable), cost
  recovery period crpyears "30", no tax credits (tax_credit_case empty, never a "+ TC" case).
  Rows with scenario "*" are scenario-independent and also count.
- ATB 2025 has no "Market" case. Use the Expanded Cost Drivers case ("Exp") where ATB publishes
  it (UtilityPV, LandbasedWind, Utility-Scale Battery Storage) and the R&D case for
  NaturalGas_FE, the only case ATB publishes for fossil plants.
- Values stay in ATB's 2023 USD. catalog.py converts them to 2024 USD.
- capex_ex_gcc = OCC + CFC * OCC / (OCC + GCC). ATB's CAPEX = OCC + GCC + CFC includes a
  generic grid-connection cost (GCC) and construction financing (CFC) on top of it. Griddy
  costs each site's interconnection explicitly (line km + substation), so the catalog removes
  GCC and GCC's share of CFC to avoid double counting.
- Battery: capex_ex_gcc(d) = power_usd_per_kw + energy_usd_per_kwh * d, fit by least squares
  over the 2, 4, 6, 8 and 10 h ATB configurations (R^2 recorded). Trajectories use 4 h.

Some facts live only in ATB's documentation pages (resource-class bins, lifetimes, reference
unit sizes, ILR), not in the CSV. DOC_FACTS below transcribes them with URLs and quotes so the
JSON is fully regenerated by this script. The PV and wind classes are picked from the site
resource estimates in DOC_FACTS with ATB's own bins.
"""

