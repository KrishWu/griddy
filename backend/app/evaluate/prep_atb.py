def select_rows(df: pd.DataFrame) -> pd.DataFrame:
    """Keep the four technologies, their chosen case, Moderate (or '*'), crpyears 30, no tax credits."""
    case = df["technology"].map(CASE_BY_TECHNOLOGY)
    keep = (
        case.notna()
        & (df["core_metric_case"] == case)
        & (df["tax_credit_case"].fillna("") == "")
        & (df["crpyears"] == CRP_YEARS)
        & df["scenario"].isin([SCENARIO, "*"])
    )
    return df[keep]


def load_atb() -> pd.DataFrame:
    """Read the ATB CSV in chunks and return only the rows the catalog can use."""
    if not RAW_CSV.exists():
        raise SystemExit(f"Missing {RAW_CSV}. Download it from {ATB_CSV_URL}")
    chunks = pd.read_csv(
        RAW_CSV,
        encoding="utf-8-sig",  # the file starts with a byte-order mark
        usecols=CSV_COLUMNS,
        dtype={c: str for c in STR_COLUMNS},
        chunksize=200_000,
    )
    df = pd.concat([select_rows(c) for c in chunks], ignore_index=True)
    assert set(df["atb_year"]) == {2025}, "expected ATB 2025 rows only"
    return df


def rows_at(df: pd.DataFrame, technology: str, techdetail: str, year: int,
            display_name: str | None = None) -> dict[str, pd.Series]:
    """{core_metric_parameter: row} for one tech detail and COD year. Fails on duplicates."""
    m = (df["technology"] == technology) & (df["techdetail"] == techdetail) & (df["core_metric_variable"] == year)
    if display_name is not None:
        m &= df["display_name"] == display_name
    sub = df[m]
    dupes = sub["core_metric_parameter"][sub["core_metric_parameter"].duplicated()]
    if not dupes.empty:
        raise ValueError(f"duplicate ATB rows for {technology}/{techdetail}/{year}: {sorted(set(dupes))}")
    return {r["core_metric_parameter"]: r for _, r in sub.iterrows()}


