def rnd(x: float) -> float:
    x = float(x)
    if not math.isfinite(x):
        raise ValueError(f"non-finite value {x}")
    return round(x, DECIMALS)


def text_or_none(x: Any) -> str | None:
    return None if x is None or (isinstance(x, float) and math.isnan(x)) else str(x)


def resource_class(value: float, bins: dict[int, tuple[float, float]]) -> int:
    """ATB class whose [min, max) bin contains value."""
    for cls, (lo, hi) in bins.items():
        if lo <= value < hi:
            return cls
    raise ValueError(f"{value} is outside every bin")


def capex_ex_gcc(occ: float, gcc: float, cfc: float) -> float:
    """CAPEX without ATB's generic grid connection and its share of construction financing."""
    return occ + cfc * occ / (occ + gcc)


def parameter_entry(row: pd.Series) -> dict[str, Any]:
    name = row["core_metric_parameter"]
    entry: dict[str, Any] = {"value": rnd(row["value"]), "units": text_or_none(row["units"])}
    if entry["units"] is None and name in UNITS_FALLBACK:
        entry["units"], entry["units_note"] = UNITS_FALLBACK[name]
    entry["ref_summary"] = text_or_none(row["ref_summary"])
    entry["ref_evidence_type"] = text_or_none(row["ref_evidence_type"])
    return entry


def parameters(rows: dict[str, pd.Series], names: tuple[str, ...]) -> dict[str, dict[str, Any]]:
    missing = [n for n in names if n not in rows]
    if missing:
        raise ValueError(f"missing ATB parameters {missing}")
    return {n: parameter_entry(rows[n]) for n in names}


def raw(rows: dict[str, pd.Series], name: str) -> float:
    """Unrounded CSV value. Derived numbers use these, never the 4-decimal JSON values."""
    return float(rows[name]["value"])


def check_capex_identity(rows: dict[str, pd.Series], what: str) -> None:
    total = raw(rows, "OCC") + raw(rows, "GCC") + raw(rows, "CFC")
    if abs(total - raw(rows, "CAPEX")) > 1e-6 * max(1.0, raw(rows, "CAPEX")):
        raise ValueError(f"{what}: OCC + GCC + CFC = {total} != CAPEX {raw(rows, 'CAPEX')}")


def derived_capex(rows: dict[str, pd.Series]) -> float:
    return capex_ex_gcc(raw(rows, "OCC"), raw(rows, "GCC"), raw(rows, "CFC"))


def trajectory(df: pd.DataFrame, technology: str, techdetail: str) -> dict[str, float]:
    """capex_ex_gcc ($/kW, 2023$) for each COD year 2027..2060."""
    m = (df["technology"] == technology) & (df["techdetail"] == techdetail) & df["core_metric_parameter"].isin(CAPEX_PARTS)
    wide = df[m].pivot(index="core_metric_variable", columns="core_metric_parameter", values="value")
    out: dict[str, float] = {}
    for year in TRAJECTORY_YEARS:
        occ, gcc, cfc = (float(wide.loc[year, p]) for p in ("OCC", "GCC", "CFC"))
        out[str(year)] = rnd(capex_ex_gcc(occ, gcc, cfc))
    return out


def linear_fit(x: list[float], y: list[float]) -> tuple[float, float, float]:
    """Least-squares y = a + b x. Returns (a, b, R^2)."""
    xs, ys = np.asarray(x, float), np.asarray(y, float)
    a_mat = np.column_stack([np.ones_like(xs), xs])
    (a, b), *_ = np.linalg.lstsq(a_mat, ys, rcond=None)
    ss_res = float(np.sum((ys - (a + b * xs)) ** 2))
    ss_tot = float(np.sum((ys - ys.mean()) ** 2))
    return float(a), float(b), 1.0 - ss_res / ss_tot


def verification(*facts: dict[str, Any]) -> dict[str, Any]:
    """verified/verification_note for one or more DOC_FACTS entries (true only if all are verified)."""
    notes = [f["verification_note"] for f in facts if f.get("verification_note")]
    return {"verified": all(f.get("verified", False) for f in facts),
            "verification_note": " ".join(notes) if notes else None}


def doc_ref(fact: dict[str, Any], quote: str | None = None) -> dict[str, Any]:
    return {"source": fact["source"], "url": fact["url"], "quote": quote or fact["quote"], **verification(fact)}


