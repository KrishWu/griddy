def pv_class_choice() -> tuple[int, str, dict[str, Any]]:
    ghi, bins = DOC_FACTS["site_ghi"], DOC_FACTS["pv_resource_classes"]
    cls = resource_class(ghi["value"], bins["bins"])
    alt = resource_class(ghi["cross_check_value"], bins["bins"])
    lo, hi = bins["bins"][cls]
    rationale = (
        f"ATB bins utility PV by mean GHI. The Kern County site (lat {ghi['lat']}, lon {ghi['lon']}) has "
        f"GHI {ghi['value']} kWh/m2/day in NLR's NSRDB PSM V3 TMY (PVWatts v8, horizontal array), inside "
        f"the Class {cls} bin ({lo}-{hi} kWh/m2/day). It sits near the lower edge, and the legacy "
        f"Perez-SUNY 2012 model gives {ghi['cross_check_value']} (Class {alt}). ATB itself bins whole "
        f"counties by county-mean GHI; this is the site's point value, and the Kern County mean was not "
        f"computed. ATB 2025 CAPEX and O&M are "
        f"identical across PV classes, so the class only sets the reference capacity factor. Griddy's "
        f"simulation uses hourly weather, not this CF."
    )
    evidence = {
        "site_ghi_kwh_m2_day": ghi["value"],
        "class_bin_kwh_m2_day": [lo, hi],
        "ghi_source": ghi["source"],
        "ghi_url": ghi["url"],
        "ghi_note": ghi["note"],
        "bins_source": bins["source"],
        "bins_url": bins["url"],
        "bins_quote": bins["quote"],
        **verification(bins, ghi),
    }
    return cls, rationale, evidence


def wind_class_choice() -> tuple[int, str, dict[str, Any]]:
    ws, bins = DOC_FACTS["tehachapi_wind_speed"], DOC_FACTS["wind_speed_classes"]
    shear = (bins["height_m"] / ws["height_m"]) ** bins["shear_exponent"]
    at_110 = ws["value"] * shear
    cls = resource_class(at_110, bins["bins"])
    alt = resource_class(ws["capacity_weighted_mean"] * shear, bins["bins"])
    lo, hi = bins["bins"][cls]
    rationale = (
        f"ATB bins land-based wind by mean wind speed at 110 m. {ws['n_sites']} NLR WIND Toolkit sites in "
        f"the Tehachapi area of Kern County average {ws['value']} m/s at 100 m (2007-2013; median "
        f"{ws['median']}). ATB's 0.14 shear exponent scales that to {at_110:.2f} m/s at 110 m, inside the "
        f"Class {cls} bin ({lo}-{hi} m/s). Class 4 is also ATB's representative class. The value is at the "
        f"Class 4/5 edge: the capacity-weighted mean gives {ws['capacity_weighted_mean'] * shear:.2f} m/s "
        f"(Class {alt}). In 2027, ATB CAPEX and O&M are identical for Classes 1-7, so the class only sets "
        f"the reference capacity factor. Griddy's simulation uses hourly weather, not this CF."
    )
    evidence = {
        "area_mean_wind_speed_100m_m_s": ws["value"],
        "area_median_wind_speed_100m_m_s": ws["median"],
        "area_capacity_weighted_mean_100m_m_s": ws["capacity_weighted_mean"],
        "n_wtk_sites": ws["n_sites"],
        "site_filter": ws["site_filter"],
        "shear_exponent": bins["shear_exponent"],
        "mean_wind_speed_110m_m_s": rnd(at_110),
        "class_bin_m_s_at_110m": [lo, hi],
        "wind_speed_source": ws["source"],
        "wind_speed_url": ws["url"],
        "wind_speed_doc_url": ws["doc_url"],
        "wind_speed_doc_quote": ws["quote"],
        "wind_speed_note": ws["note"],
        "bins_source": bins["source"],
        "bins_url": bins["url"],
        "bins_quote": bins["quote"],
        "shear_quote": bins["shear_quote"],
        **verification(bins, ws),
    }
    return cls, rationale, evidence


